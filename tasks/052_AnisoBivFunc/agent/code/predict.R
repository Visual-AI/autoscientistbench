# Protocol adapter: original fast estimator receives pre-materialized observations.
suppressPackageStartupMessages({library(purrr);library(pracma)})
source('sim/fast_kernels.R')
for (f in c('utils.R','dgp.R','smoothing.R','parameters.R','angle_estim.R','ani_detect.R')) source(file.path('R',f))
a<-commandArgs(TRUE)
getarg<-function(name){i<-match(name,a);if(is.na(i)||i==length(a))stop(paste('missing',name));a[i+1]}
input<-getarg('--input');output<-getarg('--output');model<-getarg('--model')
stopifnot(file.exists(file.path(model,'seed.txt')))
set.seed(as.integer(Sys.getenv('BENCH_SEED','1')))
cpus<-max(1L,as.integer(Sys.getenv('BENCH_CPUS','1')))
manifest<-read.csv(file.path(input,'manifest.csv'),stringsAsFactors=FALSE,colClasses=c('character','character','numeric','integer','integer'))
stopifnot(identical(names(manifest),c('id','file','offset','N','side')),nrow(manifest)>0,!anyDuplicated(manifest$id))
run<-function(k){
 row<-manifest[k,];side<-row$side;xout<-seq(0,1,length.out=side)
 f<-file(file.path(input,row$file),'rb');on.exit(close(f))
 seek(f,where=row$offset,origin='start')
 values<-readBin(f,'double',n=row$N*side^2,size=8,endian='little')
 stopifnot(length(values)==row$N*side^2,all(is.finite(values)))
 X_list<-lapply(seq_len(row$N),function(i){ix<-(i-1)*side^2+seq_len(side^2);list(t=xout,X=matrix(values[ix],nrow=side,ncol=side))})
 delta_learn<-1/sqrt(side);delta_grid<-seq(1/sqrt(side),0.4,length.out=15)
 g_hat<-estimate_angle_f(X_list=X_list,xout=xout,delta=delta_learn)
 alpha_hat<-identify_angle_f(angles=g_hat,X_list=X_list,dout=delta_grid,xout=xout,sigma=g_hat$sigma_hat)
 adj<-angle_correct_f(X_list=X_list,xout=xout,g_hat=g_hat$g_hat,alpha_hat=alpha_hat$alpha,delta=delta_learn,Hmax=alpha_hat$H_max,Hmin=g_hat$H_min,sigma=g_hat$sigma_hat)
 data.frame(id=row$id,alpha_hat_adj=as.numeric(adj$alpha_adj),stringsAsFactors=FALSE)
}
res<-parallel::mclapply(seq_len(nrow(manifest)),run,mc.cores=cpus,mc.preschedule=TRUE)
stopifnot(all(vapply(res,is.data.frame,logical(1))))
write.csv(do.call(rbind,res),output,row.names=FALSE,quote=FALSE)
cat(sprintf('predicted %d complete learning sets with %d worker(s)\n',nrow(manifest),cpus))
