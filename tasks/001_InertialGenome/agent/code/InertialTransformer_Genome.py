                # dist_pred = sample_pred_dist_norm[~sample_mask_2d].cpu().numpy()
                # dscc = spearmanr(dist_truth, dist_pred)[0]
                
                dist_truth = sample_true_dist[use_mask].cpu().numpy() 
                dist_pred = sample_pred_dist_norm[use_mask].cpu().numpy() 
                dscc = spearmanr(dist_truth, dist_pred)[0]                

                diff = dist_pred - dist_truth
                drmse = np.sqrt(np.mean(diff**2))
                

                total_dscc += dscc
                total_drmse += drmse
                total_samples += 1

                non_padding_mask = ~sample_mask
