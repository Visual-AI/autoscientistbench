    chromosome_results = {}
    total_dscc = 0.0
    total_drmse = 0.0
    total_samples = 0

    with torch.no_grad():
        test_bar = tqdm(test_loader, desc="Testing")
        for batch in test_bar:
            coords = batch['coords'].to(device)                # [B, L, 3]
            mask = batch['mask'].to(device)                    # [B, L]
            true_dist = batch['true_dist'].to(device)          # [B, L, L]
