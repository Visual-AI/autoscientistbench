            chromosome_ids = batch['chromosome_id'].tolist()  
            max_norms = batch['max_norm'].to(device)           # [B]
            
            batch_size = coords.shape[0]
            
            pred_coords, pred_dist_norm = model(idx, coords)
            
            pred_coords_denorm = pred_coords * max_norms.unsqueeze(1).unsqueeze(2)
            true_coords_denorm = coords * max_norms.unsqueeze(1).unsqueeze(2)
            pred_coords_denorm = pred_coords_denorm / 100
            true_coords_denorm = true_coords_denorm / 100

            for i in range(batch_size):
                sample_coords = coords[i]
                sample_mask = mask[i]
                sample_true_dist = true_dist[i]
                sample_contact_valid = contact_valid_mask[i]
                sample_pred_dist_norm = pred_dist_norm[i]
                sample_pred_coords = pred_coords_denorm[i]
                sample_true_coords = true_coords_denorm[i]
