                sample_mask_2d = sample_mask_2d | eye_mask

                use_mask = sample_contact_valid & (~sample_mask_2d)
                ignore_mask = ~use_mask               
                # loss = F.mse_loss(
                #     sample_pred_dist_norm[~sample_mask_2d], 
