                # ).item()
                # loss = hybrid_loss(sample_pred_dist_norm, sample_true_dist, sample_mask_2d, alpha=0.7, lambda_=0.1)
                loss = hybrid_loss(sample_pred_dist_norm, sample_true_dist, ignore_mask, alpha=0.5, lambda_=0.1)  # 0 0.1 0.5 1                
