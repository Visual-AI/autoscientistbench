def save_test_results(results, save_dir):

    os.makedirs(save_dir, exist_ok=True)
    metrics_data = []
    
    for file_name, data in results.items():
        chrom_id = data['chromosome']
        pred_coords = data['pred_coords'].numpy()
        true_coords = data['true_coords'].numpy()
        metrics = data['metrics']
        
        metrics_data.append({
            'file': file_name,
            'chromosome': chrom_id,
            'loss': metrics['loss'],
            'drmse': metrics['drmse'],
            'dscc': metrics['dscc']
        })

        pred_df = pd.DataFrame(pred_coords, columns=['X_pred', 'Y_pred', 'Z_pred'])
        true_df = pd.DataFrame(true_coords, columns=['X_true', 'Y_true', 'Z_true'])
        combined_df = pd.concat([pred_df, true_df], axis=1)
        
        save_name = file_name.replace(".csv", "_predictions.csv")
        combined_df.to_csv(os.path.join(save_dir, save_name), index=False)
    
    metrics_df = pd.DataFrame(metrics_data)
    metrics_df.to_csv(os.path.join(save_dir, "test_metrics.csv"), index=False)
    
