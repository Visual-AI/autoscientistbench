def weighted_mse_loss(pred_dist, true_dist, mask_2d, eps=1e-8):

    valid_mask = ~mask_2d
    
    valid_true = true_dist[valid_mask]
    valid_pred = pred_dist[valid_mask]
    
    unique_vals, inverse_indices = torch.unique(valid_true, return_inverse=True)
    n_groups = len(unique_vals)
    
    if n_groups < 2:
        return torch.mean((valid_pred - valid_true)**2)
    
    sorted_idx = torch.argsort(unique_vals)
    reverse_ranks = n_groups - torch.argsort(sorted_idx)
    
    ranks = reverse_ranks.float() 
    weight_denominator = n_groups * (n_groups + 1) / 2 + eps
    weights_per_val = ranks / weight_denominator  
    
    group_weights = weights_per_val[inverse_indices]

    squared_errors = (valid_pred - valid_true) ** 2
    
    group_errors = torch.zeros(n_groups, device=valid_true.device)
    group_counts = torch.zeros(n_groups, dtype=torch.long, device=valid_true.device)
    
    group_errors.scatter_add_(0, inverse_indices, squared_errors)
    group_counts.scatter_add_(0, inverse_indices, torch.ones_like(inverse_indices, dtype=torch.long))
    
    group_means = group_errors / (group_counts.float() + eps)
    loss = torch.sum(weights_per_val * group_means)
    
    return loss

def weighted_mae_loss(pred_dist, true_dist, mask_2d, eps=1e-8):

    valid_mask = ~mask_2d
    
    valid_true = true_dist[valid_mask]
    valid_pred = pred_dist[valid_mask]
    
    unique_vals, inverse_indices = torch.unique(valid_true, return_inverse=True)
    n_groups = len(unique_vals)
    
    if n_groups < 2:
        return torch.mean(torch.abs(valid_pred - valid_true))
    
    sorted_idx = torch.argsort(unique_vals)
    reverse_ranks = n_groups - torch.argsort(sorted_idx)
    
    ranks = reverse_ranks.float()
    weight_denominator = n_groups * (n_groups + 1) / 2 + eps
    weights_per_val = ranks / weight_denominator
    
    group_weights = weights_per_val[inverse_indices]
    
    absolute_errors = torch.abs(valid_pred - valid_true)
    
    group_errors = torch.zeros(n_groups, device=valid_true.device)
    group_counts = torch.zeros(n_groups, dtype=torch.long, device=valid_true.device)
    
    group_errors.scatter_add_(0, inverse_indices, absolute_errors)
    group_counts.scatter_add_(0, inverse_indices, torch.ones_like(inverse_indices, dtype=torch.long))
    
    group_means = group_errors / (group_counts.float() + eps)
    loss = torch.sum(weights_per_val * group_means)
    
    return loss

def kl_structure_loss(pred_dist, true_dist, mask_2d, lambda_=0.1, eps=1e-8):

    valid_mask = (true_dist > 0) & (~mask_2d)  # [B, L, L]
    

    p = torch.exp(-true_dist)
    p = p * valid_mask 
    p = p / (p.sum(dim=1, keepdim=True) + eps)
    
    q = torch.exp(-pred_dist**2)  
    q = q * valid_mask
    q = q / (q.sum(dim=1, keepdim=True) + eps)
    
    kl_pq = (p * (torch.log(p + eps) - torch.log(q + eps))).sum(dim=1).mean()
    kl_qp = (q * (torch.log(q + eps) - torch.log(p + eps))).sum(dim=1).mean()

    loss = lambda_ * kl_pq + (1 - lambda_) * kl_qp
    return loss

def hybrid_loss(pred_dist, true_dist, mask_2d, alpha=0.7, lambda_=0.1):

    kl_loss = kl_structure_loss(pred_dist, true_dist, mask_2d, lambda_)
    
    mse_loss = weighted_mse_loss(pred_dist, true_dist, mask_2d)
    mae_loss = weighted_mae_loss(pred_dist, true_dist, mask_2d)
    
    return alpha * kl_loss + (1 - alpha) * mse_loss
